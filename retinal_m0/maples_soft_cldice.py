"""Candidate C primitives; no CLI, launch, optimizer, or changes to A0/B1/B2.

Approved CPU proposal NEXT_METHOD_PROPOSAL_v1 (2026-10-23): original A0 plus
per-crop soft-clDice. Explicit zero padding, empty-GT zero, FP32, fixed mean.
"""
from __future__ import annotations

import math
import torch
import torch.nn.functional as F
from retinal_m0.maples_core import weighted_masked_loss


def _validate(logits, gt, fov, k):
    if type(k) is not int or k < 1:
        raise ValueError('positive integer k required')
    if logits.ndim != 4 or logits.shape[1] != 1 or not logits.numel():
        raise ValueError('nonempty single-channel NCHW required')
    if any(x.shape != logits.shape or x.device != logits.device for x in (gt, fov)):
        raise ValueError('aligned same-device tensors required')
    if not all(torch.isfinite(x).all() for x in (logits, gt, fov)):
        raise ValueError('nonfinite input')
    if any(not torch.all((x == 0) | (x == 1)) for x in (gt, fov)):
        raise ValueError('binary GT and FOV required')
    if torch.any(fov.sum((1, 2, 3)) == 0):
        raise ValueError('empty_fov: no resampling')


def soft_erode_zero(x):
    """Five-site cross erosion, actual zero outside crop (not implicit +inf)."""
    v = -F.max_pool2d(-F.pad(x, (0, 0, 1, 1), value=0.), (3, 1), stride=1)
    h = -F.max_pool2d(-F.pad(x, (1, 1, 0, 0), value=0.), (1, 3), stride=1)
    return torch.minimum(v, h)


def soft_dilate_zero(x):
    return F.max_pool2d(F.pad(x, (1, 1, 1, 1), value=0.), 3, stride=1)


def soft_open_zero(x):
    return soft_dilate_zero(soft_erode_zero(x))


def soft_skeleton(x, k):
    if type(k) is not int or k < 1:
        raise ValueError('positive integer k required')
    skeleton = F.relu(x - soft_open_zero(x))
    for _ in range(k):
        x = soft_erode_zero(x)
        delta = F.relu(x - soft_open_zero(x))
        skeleton = skeleton + F.relu(delta - skeleton * delta)
    return skeleton


def soft_cldice_terms(logits, gt, fov, *, k):
    """Return unreduced FP32 terms; empty GT is differentiable exact zero."""
    _validate(logits, gt, fov, k)
    with torch.autocast(device_type=logits.device.type, enabled=False):
        z, g, f = logits.float(), gt.float(), fov.float()
        p = z.sigmoid() * f
        y = g * f
        sk_p = soft_skeleton(p, k) * f
        # GT does not require a graph, but is generated by precisely the same op.
        sk_g = soft_skeleton(y, k) * f
        axes = (1, 2, 3)
        n_g = y.sum(axes)
        n_sg = sk_g.sum(axes)
        if torch.any((n_g > 0) & (n_sg <= 0)):
            raise ValueError('nonempty_GT_has_empty_soft_skeleton')
        tp = ((sk_p * y).sum(axes) + 1.) / (sk_p.sum(axes) + 1.)
        ts = ((sk_g * p).sum(axes) + 1.) / (n_sg + 1.)
        raw = 1. - 2. * tp * ts / (tp + ts)
        per_crop = torch.where(n_g > 0, raw, z.sum(axes) * 0.)
        if not torch.isfinite(per_crop).all():
            raise ValueError('nonfinite_soft_cldice')
        return {'per_crop': per_crop, 'loss': per_crop.mean(),
                'topology_precision': tp, 'topology_sensitivity': ts,
                'GT_count': n_g, 'GT_skeleton_mass': n_sg,
                'pred_skeleton_mass': sk_p.sum(axes)}


def candidate_loss(logits, gt, fov, *, k, eta):
    """Exact eta-zero bypass; original BCE+Dice arithmetic and coefficients."""
    if type(eta) not in (int, float) or not math.isfinite(eta) or eta < 0:
        raise ValueError('finite nonnegative eta required')
    _validate(logits, gt, fov, k)
    base = weighted_masked_loss(logits, gt, fov, fov, epsilon=1e-6)
    if eta == 0:
        return base
    return base + float(eta) * soft_cldice_terms(logits, gt, fov, k=k)['loss']


def calibrate_eta(raw_ratios, *, rho=.10):
    """One Train-only deterministic gradient budget; NOT a Dev parameter scan."""
    values = tuple(float(x) for x in raw_ratios)
    if len(values) != 8 or not all(math.isfinite(x) and x > 0 for x in values):
        raise ValueError('eight positive finite raw parameter-gradient ratios required')
    if rho != .10:
        raise ValueError('approved rho=.10 only')
    return min(1., rho / max(values))
